// Настройки рендера 2.5D, общие для конфига и для самих партов.
//
// Партам движок конфиг не отдаёт: фабрика зовёт их как
// `new Part(data, assets, dependencies, context)` (движок,
// components/model/Game.js), а `dependencies` — только сервисы. Поэтому
// единственный источник этих чисел — модуль: `src/config/client.js` кладёт
// его в `parts.seeThrough` / `parts.parallax` / `parts.volume` (документация
// клиентского конфига), а `src/client/levelView.js`,
// `src/client/parallax.js` и парты импортируют его напрямую. Правка здесь
// меняет обе стороны сразу.

// прозрачность уровней НАД игроком (задачи 2 и 3 мастер-плана)
export const seeThrough = {
  // 'hole'  — радиальная дыра вокруг игрока (по умолчанию, GTA 2)
  // 'layer' — прежнее поведение: гаснет весь слой целиком
  mode: 'hole',

  // мировые единицы: радиус дыры вокруг игрока (режим 'hole')
  radius: 260,

  // доля радиуса, уходящая на затухание края дыры
  softness: 0.45,

  // прозрачность в центре дыры
  minAlpha: 0.12,

  // режим 'layer': прозрачность всей плиты (прежний UNDER_BRIDGE_ALPHA)
  layerAlpha: 0.4,

  // скорость перехода (доля в секунду): мгновенный скачок читается как
  // мигание при каждом въезде под край моста
  fadeRate: 6,

  // затемнение уровней НИЖЕ игрока: «темнее — значит ниже»
  lowerTint: 0xb0b0c0,
};

// проекция 2.5D: одно число на всех потребителей высоты. Объект на высоте
// h (в УРОВНЯХ) рисуется смещённым ОТ центра камеры на `h * shear` долей
// расстояния до него — так читается высота в GTA 2. Потребители: слой
// уровня N и его объём (`Map`), клин рампы, корпус танка, следы
// (`src/client/parallax.js` — единственное место, где живёт формула).
//
// Число одно и для слоя, и для танка НЕ случайно: танк на плите уровня 1
// обязан смещаться ровно так же, как сама плита, иначе он с неё съедет.
//
// Масштаб — часть ТОЙ ЖЕ проекции: объект на высоте z рисуется смещённым на
// `z * shear` И увеличенным в `(1 + z * shear)` раз, ровно как плита, на
// которой он стоит (`applyParallax` делает и то, и другое одним
// трансформом). Отдельного коэффициента масштаба высоты нет — иначе танк,
// дым и бомба разъезжались бы с плитой и друг с другом.
export const parallax = {
  // сдвиг на один уровень высоты, доля расстояния до центра камеры
  shear: 0.22,

  // шаг zIndex между уровнями (`src/client/levelZ.js`). Обязан быть больше
  // любого базового zIndex парта, иначе слой моста провалится под наземный
  // навес
  levelZStride: 100,
};

// объёмные элементы карты (задача 7): экструзия рендер-слоя срезами
export const volume = {
  // путь отхода: false выключает экструзию слоёв и клин рампы
  enabled: true,

  // число срезов экструзии: цена эффекта — K вызовов отрисовки на слой.
  // Только для ОБЪЁМОВ слоёв (здания, перила): у них боковая грань
  // вертикальная, ступеней на картинке нет
  slices: 4,

  // сегментов клина рампы на клетку прогона. Клин — наклонная плоскость
  // (один меш на прогон), и это плотность его вершин: сдвиг параллакса
  // вдоль прогона растёт квадратично, поэтому ломаная из 4 сегментов на
  // клетку от него уже неотличима
  rampSegments: 4,

  // затемнение боковых граней
  sideTint: 0x9aa0aa,
};

// признаки высоты у танка (`src/client/parts/Tank.js`): масштаб корпуса и
// его тень. Не «настройка вкуса», а числа 2.5D — живут рядом с параллаксом.
//
// Тень рисуется ТОЛЬКО в полёте: она показывает отрыв от опоры, а у
// стоящего и едущего танка отрыва нет
export const shadow = {
  // тень растёт и бледнеет с ВЫСОТОЙ ОТРЫВА от опоры
  scaleGain: 0.1,
  baseAlpha: 0.4,
  alphaFalloff: 0.12,

  // доля от ДЛИНЫ корпуса: текстура тени уже в его пропорции, поэтому в
  // начале прыжка тень лежит ровно под корпусом и из-под него не
  // выглядывает
  sizeFactor: 1.05,
};

// наклон корпуса на рампе и в полёте (`src/client/tilt.js`,
