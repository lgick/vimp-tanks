// просадка корпуса на приземлении (`src/client/parts/Tank.js`): чем
// быстрее касание, тем сильнее сжатие.
// minImpact/fullImpact численно повторяют `levels.landingShake` из
// src/config/game.js (тряска камеры, считается в ядре): общего источника
// у клиентского рендера и WASM нет, менять только парой — иначе будет
// камера без пыли или пыль без камеры
export const landing = {
  // вертикальная скорость касания (уровней/с), дающая полную просадку
  fullImpact: 6,

  // максимальное сжатие корпуса по вертикали (доля). 0.22 на каждом
  // прыжке читалось как «танк складывается»; просадка обязана быть
  // заметной, но не менять силуэт
  squash: 0.14,

  // длительность просадки и возврата, мс
  duration: 260,

  // порог |vz| касания, ниже которого приземление считается мягким:
  // ни просадки, ни пыли, ни звука
  minImpact: 1.5,
};
